// Compiles ../../contracts/SimpleStorage.sol and writes the ABI + bytecode
// to src/contracts/simpleStorage.generated.ts.
// Run after changing the contract: npm run compile:contract
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(here, "../../contracts/SimpleStorage.sol");
const outPath = resolve(here, "../src/contracts/simpleStorage.generated.ts");

// paris bytecode runs on LAB Chain (Prague), Ganache GUI 7.7 (Merge) and Remix VM
const EVM_VERSION = "paris";

const input = {
  language: "Solidity",
  sources: { "SimpleStorage.sol": { content: readFileSync(sourcePath, "utf8") } },
  settings: {
    evmVersion: EVM_VERSION,
    optimizer: { enabled: false },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } }
  }
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join("\n"));
  process.exit(1);
}

const { abi, evm } = output.contracts["SimpleStorage.sol"].SimpleStorage;
const version = solc.version().split("+")[0];

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/compile-contract.mjs — do not edit by hand.
// Source: workshop/contracts/SimpleStorage.sol · solc ${version} · EVM ${EVM_VERSION} · optimizer off
export const SIMPLE_STORAGE_ABI = ${JSON.stringify(abi, null, 2)} as const;

export const SIMPLE_STORAGE_BYTECODE =
  "0x${evm.bytecode.object}";
`
);
console.log(`Wrote ${outPath} (${evm.bytecode.object.length / 2} bytes of bytecode)`);
